// E2 reviewer-readiness observer; it is neither a source of product truth nor E3/E4 assurance.
export function assessReviewReadiness(source, {manifest, release, owners, gaps}={}) {
  const get = name => String(source[name] ?? '');
  const readme=get('README.md'), contribute=get('CONTRIBUTING.md');
  const start=get('docs/START_HERE.md'), gov=get('GOVERNANCE.md');
  const eng=get('docs/ENGINEERING_GOVERNANCE.md'), template=get('.github/PULL_REQUEST_TEMPLATE.md');
  const contract=get('docs/DOCUMENTATION_STANDARD.md');
  const claims=[];
  const test=(id,group,ok)=>claims.push({id,group,pass:!!ok});
  const has=(txt,term)=>txt.includes(term);
  const codes=['RN-01','EC-01','AO-01','MC-01','AP-01','RC-01','AR-01'];
  test('P01','product',has(readme,'ICTC — Integrated Compliance Tower Control'));
  test('P02','product',has(readme,'sistema locale di governance della conoscenza di compliance'));
  test('P03','product',has(readme,'**Home / Processi di Compliance / Evidenze ICTC**'));
  test('P04','product',codes.every(id=>new RegExp(`^\\| ${id} \\|`,'m').test(readme)));
  test('P05','product',has(readme,'non costituisce un ottavo processo business'));
  test('P06','product',has(readme,'3 priorità')&&has(readme,'one-row-per-procedure / row-list'));
  test('P07','product',has(readme,'mapping != conformità')&&has(readme,'evidenza != conclusione')&&has(readme,'proposto != deciso'));
  test('P08','product',has(readme,'L\'AI può assistere')&&has(readme,'non acquisisce autorità decisionale umana'));
  test('P09','product',has(readme,release?.contracts?.constitution||'__missing__')&&has(readme,release?.contracts?.journey||'__missing__'));
  test('P10','product',has(readme,'Native Semantic Lattice 3.2')&&has(readme,'annotation-only'));
  test('D01','documentation',has(readme,'docs/START_HERE.md')&&has(readme,'docs/REPOSITORY_ATLAS.md'));
  test('D02','documentation',has(readme,'docs/PRODUCT.md')&&has(readme,'docs/documentation-manifest.json'));
  test('D03','documentation',manifest?.entrypoint==='docs/START_HERE.md'&&Array.isArray(manifest?.documents));
  test('D04','documentation',new Set((manifest?.documents||[]).filter(x=>x.authoritative).map(x=>x.authorityTopic)).size === (manifest?.documents||[]).filter(x=>x.authoritative).length);
  test('D05','documentation',has(start,'Review readiness senza nuova authority')&&has(start,'CONTRIBUTING.md'));
  test('D06','documentation',has(contract,'Un concetto current ha un solo owner canonico')&&has(contract,'lifecycle'));
  test('A01','architecture',has(readme,'SQLite')&&has(readme,'PostgreSQL')&&has(readme,'non una prova sostitutiva'));
  test('A02','architecture',has(readme,'v3/runtime-store.mjs')&&has(readme,'v3/store.mjs'));
  test('A03','architecture',has(readme,'PDF, XML, Markdown e ZIP'));
  test('A04','architecture',has(readme,'npm ci --ignore-scripts')&&has(readme,'npm start')&&has(readme,'127.0.0.1:4173'));
  test('A05','architecture',['ICTC_PUBLIC_DEMO=1','ICTC_HOST=0.0.0.0','ICTC_ALLOW_NETWORK_BIND=1','demo-runtime-3-0','ICTC_TRUSTED_PROXY_SECRET'].every(v=>has(readme,v)));
  test('R01','review',has(contribute,'## Human review handoff (repository E2 vs GitHub E3)'));
  test('R02','review',has(contribute,'exact base/head SHA')&&has(contribute,'rollback'));
  test('R03','review',has(contribute,'review-ready')&&has(contribute,'review-enforced'));
  test('R04','review',has(contribute,'reviewer')&&has(contribute,'maintainer')&&has(contribute,'deployment operator'));
  test('R05','review',has(readme,'CODEOWNERS')&&has(readme,'non impone da solo approvazioni'));
  test('R06','review',has(template,'## Affected authority')&&has(template,'## Claim boundary')&&has(template,'## Tests and falsification'));
  test('R07','review',has(eng,'## Decisione e accettazione della review')&&has(eng,'enforcement server-side'));
  test('R08','review',has(gov,'docs/authority-matrix.yaml')&&has(gov,'GitHub'));
  test('E01','external',has(contribute,'GOV-01F')&&has(contribute,'non branch protection server-side'));
  test('E02','external',has(contribute,'GAP-022')&&has(contribute,'GAP-012'));
  test('E03','external',(gaps?.gaps||[]).some(x=>x.id==='GAP-022'&&x.status==='open'));
  test('E04','external',(gaps?.gaps||[]).some(x=>x.id==='GAP-012'&&x.status==='open'));
  test('E05','external',owners?.repositoryCoherenceDebt?.id==='D-RSC'&&['F4','F5','F7','F8'].every(id=>(owners.repositoryCoherenceDebt.findings||[]).some(x=>x.id===id)));
  test('E06','external',has(readme,'Una CI verde')&&has(readme,'non')&&has(readme,'deployment'));
  const failures=claims.filter(x=>!x.pass);
  return {ok:failures.length===0,predicates:claims.length,passed:claims.length-failures.length,failures:failures.map(x=>x.id),groups:Object.fromEntries([...new Set(claims.map(x=>x.group))].map(g=>[g,{total:claims.filter(x=>x.group===g).length,passed:claims.filter(x=>x.group===g&&x.pass).length}]))};
}
