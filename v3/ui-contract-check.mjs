import { strict as assert } from 'node:assert';
import { readdir, readFile } from 'node:fs/promises';
const publicRoot = new URL('./public/', import.meta.url);
const html = await readFile(new URL('index.html', publicRoot), 'utf8');
const cssFiles = (await readdir(publicRoot)).filter(name => name.endsWith('.css'));
const uiFiles = (await readdir(new URL('ui/', publicRoot))).filter(name => name.endsWith('.js'));
const uiSources = await Promise.all(uiFiles.map(name => readFile(new URL(`ui/${name}`, publicRoot), 'utf8')));
const js = [await readFile(new URL('app.js', publicRoot), 'utf8'), ...uiSources].join('\n');
const css = (await Promise.all(cssFiles.map(name => readFile(new URL(name, publicRoot), 'utf8')))).join('\n');

const nav=html.match(/<nav class="service-nav"[\s\S]*?<\/nav>/)?.[0]||'';
assert.ok(nav,'canonical service nav missing');
assert.equal((nav.match(/data-service=/g)||[]).length,3);
assert.deepEqual([...nav.matchAll(/data-service="([^"]+)"/g)].map(match=>match[1]),['home','processes','proof']);
for(const label of ['Oggi','Processi','Prove'])assert.ok(nav.includes(`>${label}<`),`nav label ${label}`);
assert.ok(html.includes('id="homeView"'));
assert.ok(html.includes('id="processesView"'));
assert.ok(html.includes('id="procedureHub"'));
assert.ok(html.includes('id="homePrimaryAction"'));
assert.ok(html.includes('id="homeJourney"'));
assert.ok(html.includes('Obiettivo di monitoraggio'));
assert.ok(html.includes('Racconto originale'));
assert.equal((html.match(/name="objective"[^>]*required/g)||[]).length,1);
assert.equal((html.match(/name="originalNarrative"[^>]*required/g)||[]).length,1);
assert.equal((html.match(/name="awarenessAt"[^>]*required/g)||[]).length,1);
for (const role of ['admin','user','auditor']) assert.ok(html.includes(`option value="${role}"`), `role option ${role}`);
const renderSource = uiSources[uiFiles.indexOf('render.js')];
for (const label of ['Amministratore','Utente','Auditor']) assert.ok(renderSource.includes(label), `role label ${label}`);
for(const requiredLabel of ['Verifica piano','Analisi AI','Domanda successiva','Confronto con l’originale','Suggerimento AI da verificare'])assert.ok(html.includes(requiredLabel)||js.includes(requiredLabel),requiredLabel);
for(const required of ['data-download-evidence','downloadProtected','sourceDecisionReason','pauseReason','closureNote','Riprova analisi AI','formulationVersions','observations','data-home-action','activateHomeAction'])assert.ok(js.includes(required)||html.includes(required),required);
for(const forbidden of ['tenantSelect','reviewer','semantic graph','control mapping','owner confirmation','prompt(','confirm(','Plan Reveal','AI Lens','Question Compass','Origin Diff','Control plane','Compliance evidence workspace'])assert.ok(!`${html}\n${js}`.toLowerCase().includes(forbidden.toLowerCase()),forbidden);
assert.ok(js.includes('x-ictc-expected-revision'));
assert.ok(js.includes("storageGet('ictc-service','home')"));
assert.ok(css.includes('prefers-reduced-motion'));
assert.ok(css.includes('.journey-strip'));
assert.ok(css.includes('grid-auto-flow:column'));
assert.ok(!js.includes('new MutationObserver'));
assert.ok(uiFiles.length>=5);
console.log(`ui-contract-check: ok (${uiFiles.length} UI modules, native Oggi/Processi/Prove shell, three role-correct journeys)`);
