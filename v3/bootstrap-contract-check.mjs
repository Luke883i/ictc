import assert from 'node:assert/strict';
import {existsSync,readFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {BOOTSTRAP_CONTRACT,baselineBootstrapModel,validateBootstrapModel} from './bootstrap-contract.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>readFileSync(path.join(root,p),'utf8');
const pkg=JSON.parse(read('package.json')),lock=JSON.parse(read('package-lock.json'));
assert.equal(BOOTSTRAP_CONTRACT.node.engine,pkg.engines.node);
assert.equal(lock.packages[''].engines.node,pkg.engines.node);
assert.equal(read('.nvmrc').trim(),String(BOOTSTRAP_CONTRACT.node.major));
assert.ok(!existsSync(path.join(root,'yarn.lock')),'yarn.lock would create a second package-manager authority');
assert.equal(pkg.scripts.start,'node v3/bootstrap.mjs');
assert.equal(pkg.scripts.demo,'node v3/bootstrap.mjs demo');
assert.equal(pkg.scripts.build,'npm run check');
assert.equal(pkg.scripts['bootstrap:check'],'node v3/bootstrap-contract-check.mjs');
const shell=read('ictc.sh');
assert.ok(shell.includes('PORT="${PORT:-${ICTC_PORT:-4173}}"'),'shell port precedence drift');
assert.ok(shell.includes('nohup node v3/bootstrap.mjs'),'shell must delegate foreground execution to bootstrap.mjs');
assert.ok(!shell.includes('nohup node v3/server.mjs'),'shell must not bypass bootstrap authority');
assert.ok(shell.includes('codespace) COMMAND="start"; NO_OPEN=1'),'codespace compatibility alias missing');
const postStart=read('.devcontainer/post-start.sh');
assert.ok(postStart.includes('./ictc.sh start --no-open'),'devcontainer must use canonical local supervisor');
assert.ok(!postStart.includes('ICTC_HOST=0.0.0.0'),'devcontainer must not weaken loopback default');
const runProfiles=read('docs/RUN_PROFILES.md'),readme=read('README.md');
for(const text of[runProfiles,readme]){assert.ok(text.includes('npm ci --ignore-scripts'));assert.ok(text.includes('npm start'));assert.ok(text.includes('npm run demo'));assert.ok(text.includes('./ictc.sh start'));}
assert.ok(runProfiles.includes('npm ci --ignore-scripts && npm run build'));assert.ok(runProfiles.includes('trusted-header'));
const http=read('v3/runtime/http.mjs');
assert.ok(http.includes('assertSafeRuntimeBinding'),'runtime network guard missing');
assert.ok(http.includes("ICTC_ALLOW_NETWORK_BIND==='1'"),'explicit network allow guard missing');
assert.ok(http.includes('local-identity-loopback-only'),'local identity loopback guard missing');
const result=validateBootstrapModel(baselineBootstrapModel());assert.equal(result.ok,true,result.errors.join(','));
console.log(JSON.stringify({ok:true,suite:'bootstrap-contract',authority:BOOTSTRAP_CONTRACT.authority,profiles:Object.keys(BOOTSTRAP_CONTRACT.profiles),packageManager:'npm',foreground:'v3/bootstrap.mjs',supervisor:'ictc.sh',claimBoundary:'portable execution convergence does not weaken network identity or prove deployment assurance'}));
