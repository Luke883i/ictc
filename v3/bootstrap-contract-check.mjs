import assert from 'node:assert/strict';
import {existsSync,readFileSync} from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
import {assertBootstrapTransport,BOOTSTRAP_CONTRACT,baselineBootstrapModel,deploymentPlatformProjection,resolveBootstrap,validateBootstrapModel} from './bootstrap-contract.mjs';
const root=path.resolve(path.dirname(fileURLToPath(import.meta.url)),'..');
const read=p=>readFileSync(path.join(root,p),'utf8');
const pkg=JSON.parse(read('package.json')),lock=JSON.parse(read('package-lock.json'));
assert.equal(BOOTSTRAP_CONTRACT.node.engine,pkg.engines.node);
assert.equal(lock.packages[''].engines.node,pkg.engines.node);
assert.equal(read('.nvmrc').trim(),String(BOOTSTRAP_CONTRACT.node.major));
assert.ok(!existsSync(path.join(root,'yarn.lock')),'yarn.lock would create a second package-manager authority');
assert.equal(pkg.scripts.start,'node v3/bootstrap.mjs');
assert.equal(pkg.scripts.demo,'node v3/bootstrap.mjs demo');
assert.equal(pkg.scripts.build,'npm run check');
assert.equal(pkg.scripts['bootstrap:check'],'node v3/bootstrap-contract-check.mjs');
const shell=read('ictc.sh');
assert.ok(shell.includes('PORT="${PORT:-${ICTC_PORT:-4173}}"'),'shell port precedence drift');
assert.ok(shell.includes('nohup node v3/bootstrap.mjs'),'shell must delegate foreground execution to bootstrap.mjs');
assert.ok(!shell.includes('nohup node v3/server.mjs'),'shell must not bypass bootstrap authority');
assert.ok(shell.includes('codespace) COMMAND="start"; NO_OPEN=1'),'codespace compatibility alias missing');
const postStart=read('.devcontainer/post-start.sh');
assert.ok(postStart.includes('./ictc.sh start --no-open'),'devcontainer must use canonical local supervisor');
assert.ok(!postStart.includes('ICTC_HOST=0.0.0.0'),'devcontainer must not weaken loopback default');
const runProfiles=read('docs/RUN_PROFILES.md'),readme=read('README.md');
for(const text of[runProfiles,readme]){assert.ok(text.includes('npm ci --ignore-scripts'));assert.ok(text.includes('npm start'));assert.ok(text.includes('npm run demo'));assert.ok(text.includes('./ictc.sh start'));}
assert.ok(runProfiles.includes('npm ci --ignore-scripts && npm run build'));assert.ok(runProfiles.includes('trusted-header'));
assert.ok(runProfiles.includes('ICTC_HOST=0.0.0.0'),'Render non-loopback bind guidance missing');
assert.ok(runProfiles.includes('RENDER_SERVICE_TYPE'),'Render platform diagnostic contract missing');
assert.ok(runProfiles.includes('filesystem Render è effimero'),'Render storage boundary missing');
const http=read('v3/runtime/http.mjs');
assert.ok(http.includes('assertSafeRuntimeBinding'),'runtime network guard missing');
assert.ok(http.includes("ICTC_ALLOW_NETWORK_BIND==='1'"),'explicit network allow guard missing');
assert.ok(http.includes('local-identity-loopback-only'),'local identity loopback guard missing');
const renderWebEnv={RENDER:'true',RENDER_SERVICE_TYPE:'web',PORT:'10000'};
const renderPrivateEnv={RENDER:'true',RENDER_SERVICE_TYPE:'pserv',PORT:'10000'};
const renderWorkerEnv={RENDER:'true',RENDER_SERVICE_TYPE:'worker'};
assert.equal(deploymentPlatformProjection(renderWebEnv).inbound,true);
assert.equal(deploymentPlatformProjection(renderPrivateEnv).inbound,true);
assert.equal(deploymentPlatformProjection(renderWorkerEnv).inbound,false);
assert.throws(()=>assertBootstrapTransport({host:'127.0.0.1',env:renderWebEnv}),error=>error.code==='paas-network-bind-required'&&error.platform==='render'&&error.serviceType==='web');
assert.throws(()=>assertBootstrapTransport({host:'localhost',env:renderPrivateEnv}),error=>error.code==='paas-network-bind-required');
assert.doesNotThrow(()=>assertBootstrapTransport({host:'0.0.0.0',env:renderWebEnv}));
assert.doesNotThrow(()=>assertBootstrapTransport({host:'127.0.0.1',env:renderWorkerEnv}));
assert.doesNotThrow(()=>assertBootstrapTransport({host:'127.0.0.1',env:{}}));
const renderResolved=resolveBootstrap({env:{...renderWebEnv,ICTC_HOST:'0.0.0.0'},root:'/tmp/ictc'});
assert.equal(renderResolved.port,'10000');assert.equal(renderResolved.host,'0.0.0.0');
assert.equal(BOOTSTRAP_CONTRACT.platforms.render.hostAutoOverride,false);assert.equal(BOOTSTRAP_CONTRACT.platforms.render.identityAutoTrust,false);
assert.equal(BOOTSTRAP_CONTRACT.platforms.render.filesystemDefault,'ephemeral');assert.equal(BOOTSTRAP_CONTRACT.platforms.render.persistentDiskShared,false);assert.equal(BOOTSTRAP_CONTRACT.platforms.render.persistentDiskMultiInstance,false);
assert.deepEqual(Object.keys(BOOTSTRAP_CONTRACT.profiles),['standard','demo'],'BOOTSTRAP-0 must not anticipate CEP enterprise runtime profiles');
const result=validateBootstrapModel(baselineBootstrapModel());assert.equal(result.ok,true,result.errors.join(','));
