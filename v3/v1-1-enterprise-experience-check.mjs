assert.equal(createHash('sha256').update(mark).digest('hex'),'ec4802493af95abccb5c0e0dfb949ffece385b4ce29063e999a71cf801e948fc','official project mark derivative changed');
assert.match(shell,/\/assets\/ictc-mark\.png/);
