import { strict as assert } from 'node:assert';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
const root = path.resolve(new URL('..', import.meta.url).pathname);
const services = ['monitoring','incidents'];
const roles = ['admin','user'];
const phases = ['configure','collect','review','complete'];
const disturbances = ['normal','missing-or-untrusted-input'];
const M = services.length * roles.length * phases.length * disturbances.length;
const scenarios = [];
for(const service of services) for(const role of roles) for(const phase of phases) for(const disturbance of disturbances) scenarios.push({service,role,phase,disturbance});
for(let index=0; index<100; index++) scenarios.push(scenarios[index % M]);
function primitives(s) {
  const out = new Set(['two-services-only','two-roles-only','human-review-boundary','single-global-llm-config','auditable-write']);
  out.add(`service:${s.service}`); out.add(`role:${s.role}`); out.add(`phase:${s.phase}`); out.add(`disturbance:${s.disturbance}`);
  if(s.service==='monitoring') ['editable-job-prompt','unified-contribution','eli-inspired-source','candidate-not-applicable'].forEach(v=>out.add(v));
  if(s.service==='incidents') ['facts-first','editable-ai-draft','administrative-timeline','notification-reminders-not-legal-decision'].forEach(v=>out.add(v));
  if(s.role==='admin') ['configure-provider','manage-schedule'].forEach(v=>out.add(v));
  else ['read-results','create-contribution','report-incident'].forEach(v=>out.add(v));
  if(s.disturbance!=='normal') ['explicit-missing-data','no-silent-inference'].forEach(v=>out.add(v));
  return out;
}
const known = new Set(); let lastNovelty = 0; const novelty = [];
scenarios.forEach((scenario,index)=>{let count=0; for(const primitive of primitives(scenario)) if(!known.has(primitive)){known.add(primitive);count++;} if(count) lastNovelty=index+1; novelty.push(count);});
assert.equal(scenarios.length,M+100);
assert.ok(lastNovelty<=M,`novità oltre M: ${lastNovelty}`);
assert.equal(novelty.slice(M).reduce((a,b)=>a+b,0),0,'nuove primitive dopo M');
const report={schemaVersion:'1.0.0',tranche:'abstract-product',M,MPlus100:M+100,primitiveCount:known.size,lastNoveltyScenario:lastNovelty,noveltyAfterM:0,principles:[...known].sort()};
await mkdir(path.join(root,'artifacts'),{recursive:true}); await writeFile(path.join(root,'artifacts/abstract-saturation.json'),JSON.stringify(report,null,2));
console.log(`abstract-saturation: ok (M=${M}, M+100=${M+100}, primitives=${known.size}, last novelty=${lastNovelty})`);
