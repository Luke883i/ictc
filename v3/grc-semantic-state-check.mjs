import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { runtimeOntologyProjection, semanticStateTerm } from './runtime/ontology.mjs';
const read=p=>readFile(new URL(p,import.meta.url),'utf8');
const [facade,base]=await Promise.all([read('./public/ui/grc-workspace.js'),read('./public/ui/grc-workspace-base.js')]);
const ontology=runtimeOntologyProjection();
assert.equal(ontology.schemaVersion,'1.6.0');
assert.equal(ontology.semanticVocabularyAuthority,'runtime-semantic-vocabulary');
assert.ok(facade.includes("objects:'objectLifecycle'"));
assert.ok(facade.includes("coverage:'mappingDecision'"));
assert.ok(facade.includes("actions:'actionLifecycle'"));
assert.ok(facade.includes("risks:'riskBand'"));
assert.ok(facade.includes("assurance:'assuranceLifecycle'"));
assert.ok(facade.includes("axis:'epistemicDisposition',value:'proposed'"));
assert.ok(facade.includes('semanticStateAuthority'));
assert.ok(facade.includes('Versioni approvate internamente'));
assert.ok(!facade.includes('const STATUS='));
assert.ok(base.includes('const STATUS='),'compatibility renderer must remain explicit until retirement');
assert.equal(semanticStateTerm('assuranceLifecycle','approved').label,'Versione approvata internamente');
assert.equal(semanticStateTerm('actionLifecycle','done').label,'Completata · da verificare');
assert.equal(semanticStateTerm('riskBand','critical').authority,'human-assessment');
assert.throws(()=>semanticStateTerm('riskBand','approved'),e=>e?.code==='semantic-vocabulary-missing-state');
console.log(JSON.stringify({ok:true,control:'GRC-TYPED-SEMANTIC-STATE',ontology:ontology.schemaVersion,facadeAuthority:'runtime-semantic-vocabulary',legacyStatusAuthority:false,compatibilityRenderer:true}));
