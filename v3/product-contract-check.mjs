import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { VERSION } from './version.mjs';
import { processDefinitions, surfaceProcessDefinitions } from './runtime/process-kernel.mjs';
const root=new URL('./',import.meta.url);
const contract=JSON.parse(await readFile(new URL('product-contract.json',root),'utf8'));
const packageManifest=JSON.parse(await readFile(new URL('../package.json',root),'utf8'));
const server=await readFile(new URL('server.mjs',root),'utf8');
const controller=await readFile(new URL('public/ui/controller.js',root),'utf8');
const active=await readFile(new URL('public/ui/active-experience.js',root),'utf8');
const entry=await readFile(new URL('public/ui/operational-entry.js',root),'utf8');
assert.match(VERSION,/^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/);
assert.equal(packageManifest.version,VERSION);
assert.match(server,/PRODUCT_EDITION='V3 Experimental'/);
assert.match(server,/projected\.grc=grc/);
assert.match(server,/projected\.work=workProjection/);
assert.match(server,/projected\.reviewInbox=canonicalReviewInbox/);
assert.match(server,/projected\.insights=insightProjection/);
assert.match(controller,/state\.data\.experience\?\.product/);
assert.match(active,/installV3EntryPoint\(\)/);
assert.match(entry,/id='v3OperationalHome'|root\.id='v3OperationalHome'/);
assert.equal(contract.product,'ICTC Control Tower');
assert.equal(contract.productEdition,'V3 Experimental');
assert.deepEqual(contract.permanentShell,['home','processes','proof']);
assert.deepEqual(contract.services.map(x=>x.id),['monitoring','incidents','objects','coverage','actions','risks','assurance']);
assert.deepEqual(contract.roles.map(x=>x.id),['admin','user','auditor']);
assert.equal(contract.experienceMetrics.services,7);
assert.equal(contract.orchestration.intentRouting.maxCandidates,3);
assert.equal(contract.orchestration.intentRouting.humanLaunchRequired,true);
assert.equal(contract.orchestration.workQueue.aiRanking,false);
for(const id of['objects','coverage','actions','risks','assurance'])assert.equal(surfaceProcessDefinitions().find(x=>x.id===id)?.service,'grc');
assert.equal(processDefinitions().length,12);
assert.ok(contract.roles.find(x=>x.id==='admin').permissions.includes('manage-grc'));
assert.ok(contract.roles.find(x=>x.id==='user').permissions.includes('contribute-grc'));
for(const metric of['writeReceiptCoverage','aiTraceCoverage','humanAdoptionCoverage','leastPrivilegeProjectionCoverage','linkedEvidenceCoverage','rawInputPreservation','evidenceExportCoverage','semanticRatchetCoverage','decisionProjectionCoverage','epistemicProjectionCoverage','sameAsReadExportCoverage','grcProcessCoverage','humanHeatmapCoverage','boundedCoverageMetric','persistentTodoCoverage','progressiveDisclosureCoverage','unifiedWorkQueueCoverage','humanProcedureSelectionCoverage','procedureGuideCoverage','assistEnvelopeCoverage','reviewInboxCoverage','deterministicInsightCoverage','humanInsightValidationCoverage','procedureTraceCoverage','v3Saturation100kCoverage'])assert.equal(contract.experienceMetrics[metric],1,metric);
assert.equal(contract.experienceMetrics.maxPrimaryActionsPerContext,1);
assert.equal(contract.experienceMetrics.roleLeakage,0);
assert.ok(contract.experiencePrinciples.every(x=>x.length>25));
assert.ok(contract.boundaries.some(x=>x.includes('V3 Experimental')));
assert.ok(contract.boundaries.some(x=>x.includes('declared universe')));
assert.ok(contract.boundaries.some(x=>x.includes('heatmap')));
assert.ok(contract.boundaries.some(x=>x.includes('routing')));
assert.ok(contract.boundaries.some(x=>x.includes('KPI')));
console.log(`product-contract-check: ok (${contract.productEdition}, ${contract.services.length} services, ${contract.roles.length} roles, runtime ${VERSION})`);
