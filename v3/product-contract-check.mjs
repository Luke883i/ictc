import { strict as assert } from 'node:assert';
import { readFile } from 'node:fs/promises';
import { VERSION } from './version.mjs';
await import('./api-contract-check.mjs');
const root = new URL('./', import.meta.url);
const contract = JSON.parse(await readFile(new URL('product-contract.json', root), 'utf8'));
const dod = JSON.parse(await readFile(new URL('product-dod.json', root), 'utf8'));
const invariants = JSON.parse(await readFile(new URL('experience-invariants.json', root), 'utf8'));
const packageManifest = JSON.parse(await readFile(new URL('../package.json', root), 'utf8'));
const serverSource = await readFile(new URL('server.mjs', root), 'utf8');
const controllerSource = await readFile(new URL('public/ui/controller.js', root), 'utf8');
assert.match(VERSION, /^\d+\.\d+\.\d+(?:-[0-9A-Za-z.-]+)?$/, 'runtime release identity must be semver-like');
assert.equal(packageManifest.version, VERSION, 'package.json version must equal v3/version.mjs VERSION');
assert.match(serverSource, /version:VERSION/, 'health/runtime version must derive from VERSION');
assert.match(serverSource, /projected\.experience\.release=VERSION/, 'bootstrap release must derive from VERSION');
assert.match(controllerSource, /document\.title=`ICTC \$\{state\.data\.version\} · Enterprise Workbench`/, 'browser title must derive from bootstrap runtime version');
assert.deepEqual(contract.services.map(item=>item.id), ['monitoring','incidents']);
assert.deepEqual(contract.roles.map(item=>item.id), ['admin','user','auditor']);
assert.equal(contract.controlPlane.id, 'administration');
assert.equal(contract.experienceMetrics.services, 2);
assert.equal(contract.experienceMetrics.roles, 3);
assert.ok(contract.experienceMetrics.monitoringMissionRequiredQuestions <= 1);
assert.equal(contract.experienceMetrics.incidentIntakeRequiredQuestions, 2);
for (const metric of ['writeReceiptCoverage','aiTraceCoverage','humanAdoptionCoverage','formulationVersionCoverage','monitoringLifecycleCoverage','aiRecoveryCoverage','reasonedDecisionCoverage','leastPrivilegeProjectionCoverage','linkedEvidenceCoverage','rawInputPreservation','evidenceExportCoverage','aiBudgetCoverage','userLifecycleCoverage','readinessCoverage']) assert.equal(contract.experienceMetrics[metric],1,metric);
assert.equal(contract.experienceMetrics.maxPrimaryActionsPerContext,1);
assert.equal(contract.experienceMetrics.roleLeakage,0);
assert.ok(contract.experiencePrinciples.every(item => item.length > 25));
assert.ok(contract.wowMechanisms.length >= 7);
assert.ok(contract.boundaries.some(item=>item.includes('non determina')));
assert.ok(contract.boundaries.some(item=>item.includes('non verità')));
assert.ok(dod.criteria.length >= 35);
assert.ok(invariants.invariants.length >= 18);
for (const forbidden of ['reviewer','owner','analyst','viewer','tenant']) assert.ok(!contract.roles.some(role=>role.id===forbidden));
console.log(`product-contract-check: ok (${contract.services.length} services, ${contract.roles.length} roles, release ${VERSION}, control plane ${contract.controlPlane.id})`);
