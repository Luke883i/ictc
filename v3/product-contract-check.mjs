import { strict as assert } from 'node:assert';
import { readFile } from 'node:fs/promises';
const root = new URL('./', import.meta.url);
const contract = JSON.parse(await readFile(new URL('product-contract.json', root), 'utf8'));
const dod = JSON.parse(await readFile(new URL('product-dod.json', root), 'utf8'));
assert.deepEqual(contract.services.map(item=>item.id), ['monitoring','incidents']);
assert.deepEqual(contract.roles.map(item=>item.id), ['admin','user']);
assert.equal(contract.experienceMetrics.services, 2);
assert.equal(contract.experienceMetrics.roles, 2);
assert.ok(contract.experienceMetrics.monitoringMissionRequiredQuestions <= 1);
assert.equal(contract.experienceMetrics.incidentIntakeRequiredQuestions, 2);
assert.equal(contract.experienceMetrics.maxPrimaryActionsPerContext, 1);
assert.equal(contract.experienceMetrics.writeReceiptCoverage, 1);
assert.equal(contract.experienceMetrics.aiTraceCoverage, 1);
assert.ok(contract.experiencePrinciples.every(item => item.length > 20));
assert.ok(contract.wowMechanisms.length >= 5);
assert.ok(contract.boundaries.some(item=>item.includes('non determina')));
assert.ok(dod.criteria.length >= 20);
for (const forbidden of ['reviewer','owner','analyst','viewer','tenant']) assert.ok(!contract.roles.some(role=>role.id===forbidden));
console.log(`product-contract-check: ok (${contract.services.length} services, ${contract.roles.length} roles, ${dod.criteria.length} DoD)`);
