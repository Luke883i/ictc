import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const root=new URL('./',import.meta.url);
const active=await readFile(new URL('public/ui/active-experience.js',root),'utf8');
const entry=await readFile(new URL('public/ui/operational-entry.js',root),'utf8');
const styles=await readFile(new URL('public/styles.css',root),'utf8');
const entryCss=await readFile(new URL('public/operational-entry.css',root),'utf8');
const grc=await readFile(new URL('public/ui/grc-workspace.js',root),'utf8');
const contract=JSON.parse(await readFile(new URL('product-contract.json',root),'utf8'));
assert.equal(contract.productEdition,'V3 Experimental');
assert.deepEqual(contract.permanentShell,['home','processes','proof']);
assert.equal((active.match(/installV3EntryPoint\(\)/g)||[]).length,1,'one operational entry install');
assert.equal((active.match(/installGrcWorkspace\(\)/g)||[]).length,1,'one GRC workspace install');
assert.match(active,/dataset\.ictcEdition='v3-experimental'/);
assert.doesNotMatch(active,/data-service="objects"|data-service="coverage"|data-service="actions"|data-service="risks"|data-service="assurance"/);
assert.match(entry,/id='v3OperationalHome'|root\.id='v3OperationalHome'/);
assert.equal((entry.match(/id=\"v3IntentForm\"/g)||[]).length,1,'single operational input');
assert.match(entry,/Trova la procedura/);
assert.match(entry,/Nessuna procedura parte senza la tua scelta/);
assert.match(entry,/Scegli la procedura/);
assert.match(entry,/Ingresso/);
assert.match(entry,/Uscita attesa/);
assert.match(entry,/AI · proposta soltanto/);
assert.match(entry,/Richiede persona/);
assert.match(entry,/Prossimo lavoro/);
assert.match(entry,/Decisioni da rivedere/);
assert.match(entry,/Indicatori deterministici/);
assert.match(entry,/Valida la lettura AI/);
assert.doesNotMatch(entry,/\bprompt\s*\(|\bconfirm\s*\(/);
assert.doesNotMatch(grc,/\bprompt\s*\(|\bconfirm\s*\(/);
assert.match(styles,/grc-workspace\.css/);
assert.match(styles,/operational-entry\.css/);
assert.doesNotMatch(styles,/grc-v2\.css/);
assert.match(entryCss,/#grcCockpit\{display:none!important\}/);
assert.match(entryCss,/@media\(prefers-reduced-motion:reduce\)/);
