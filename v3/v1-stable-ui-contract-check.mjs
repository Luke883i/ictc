import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { DISCLOSURE, PROCESS_SPECS, SURFACES } from './v1-stable-experience-model.mjs';
const active=await readFile(new URL('./public/ui/active-experience.js',import.meta.url),'utf8');
const globalTools=await readFile(new URL('./public/ui/global-tools.js',import.meta.url),'utf8');
const css=await readFile(new URL('./public/stable-experience.css',import.meta.url),'utf8');
const styles=await readFile(new URL('./public/styles.css',import.meta.url),'utf8');
const html=await readFile(new URL('./public/index.html',import.meta.url),'utf8');
assert.deepEqual(SURFACES.map(x=>x.id),['home','processes','proof']);
assert.equal(Object.keys(PROCESS_SPECS).length,7);
assert.equal(DISCLOSURE.length,5);
assert.deepEqual(DISCLOSURE.map(x=>x.level),[1,2,3,4,5]);
for(const forbidden of ['installBusinessNexus','installProcessLandscape','installV3EntryPoint','installNoviceEntry','installExperiencePolish','installProcedureGuideLanguageBinding'])assert.ok(!active.includes(forbidden),`duplicate presentation owner active: ${forbidden}`);
assert.match(active,/data.*ictcExperience|ictcExperience='stable-1'/);
assert.match(active,/filter\(item=>item\.code&&item\.id!=='evidence'\)/);
assert.match(active,/stable-process-card/);
assert.match(active,/\.home-journey-panel.*hidden/);
assert.match(active,/\.home-overview-grid.*hidden/);
assert.ok(!globalTools.includes('downloadCurrentView'),'export must not live in permanent header');
assert.ok(globalTools.includes('placeholder="Cerca…"'));
assert.match(styles,/stable-experience\.css/);
assert.match(css,/home-journey-panel/);
assert.match(css,/display:none!important/);
assert.match(css,/procedure-hub/);
const nav=html.match(/<nav class="service-nav"[\s\S]*?<\/nav>/)?.[0]||'';
assert.deepEqual([...nav.matchAll(/data-service="([^"]+)"/g)].map(x=>x[1]),['home','processes','proof']);
console.log('v1-stable-ui-contract-check: ok (3 surfaces, 7 processes, 5 disclosure levels, single process catalog owner)');
