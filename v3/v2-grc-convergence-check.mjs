import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
const server=await readFile(new URL('./server.mjs',import.meta.url),'utf8');
const handlerRegistry=await readFile(new URL('./runtime/runtime-handler-registry.mjs',import.meta.url),'utf8');
const kernel=JSON.parse(await readFile(new URL('./process-kernel.json',import.meta.url),'utf8'));
const projection=await readFile(new URL('./runtime/grc-projection.mjs',import.meta.url),'utf8');
const evidence=await readFile(new URL('./runtime/grc-evidence-store.mjs',import.meta.url),'utf8');
assert.ok(server.includes('createRuntimeHandlers'),'registry-driven runtime handler composition missing');
assert.ok(handlerRegistry.includes('createGrcRuntime'),'shared GRC runtime missing from runtime handler registry');
assert.ok(server.includes('createGrcEvidenceStore'),'shared GRC evidence store missing');
const kernelIds=new Set((kernel.processes||kernel.procedures||kernel.services||[]).map(item=>item.id));
for(const id of ['objects','coverage','actions','risks','assurance'])assert.ok(kernelIds.has(id),`kernel missing ${id}`);
for(const key of ['objects','coverage','actions','risks','assurance','dashboard'])assert.ok(projection.includes(key),`projection missing ${key}`);
for(const key of ['grc-object','mapping','action','risk','assurance-case'])assert.ok(evidence.includes(key),`evidence route missing ${key}`);
console.log('v2-grc-convergence-check: ok (GRC authority follows runtime handler registry)');
