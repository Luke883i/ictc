import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { surfaceProcessDefinitions } from './runtime/process-kernel.mjs';
const root=new URL('./',import.meta.url);
const contract=JSON.parse(await readFile(new URL('product-contract.json',root),'utf8'));
const semantic=JSON.parse(await readFile(new URL('semantic-api-contract.json',root),'utf8'));
const pkg=JSON.parse(await readFile(new URL('../package.json',root),'utf8'));
const dod=await readFile(new URL('../docs/V3_EXPERIMENTAL_DOD.md',root),'utf8');
const active=await readFile(new URL('public/ui/active-experience.js',root),'utf8');
const styles=await readFile(new URL('public/styles.css',root),'utf8');
const server=await readFile(new URL('server.mjs',root),'utf8');
const workflow=await readFile(new URL('../.github/workflows/v3-dod.yml',root),'utf8');
assert.equal(contract.productEdition,'V3 Experimental');
assert.equal(semantic.schemaVersion,'3.0.0');
assert.deepEqual(contract.permanentShell,['home','processes','proof']);
assert.equal(surfaceProcessDefinitions().filter(x=>x.kind==='service').length,8,'7 business services + evidence surface');
for(const id of['monitoring','incidents','objects','coverage','actions','risks','assurance'])assert.ok(surfaceProcessDefinitions().some(x=>x.id===id),id);
for(const field of['work','reviewInbox','insights','decisions','epistemic','exports'])assert.ok(semantic.fields[field],`semantic field missing: ${field}`);
assert.equal(semantic.fields.work.humanLaunchRequired,true);
assert.equal(semantic.fields.insights.validationAuthority,'human');
assert.match(server,/projected\.homeNextAction=projected\.work\.queue\.nextAction/);
assert.equal((active.match(/installV3EntryPoint\(\)/g)||[]).length,1);
assert.doesNotMatch(styles,/grc-v2\.css/);
for(const test of['work-orchestration-check.mjs','procedure-guide-check.mjs','assist-envelope-check.mjs','review-inbox-check.mjs','insight-projection-check.mjs','procedure-trace-check.mjs','v3-saturation-100k.mjs'])assert.ok(pkg.scripts['test:contract'].includes(test),`core V3 contract test not wired: ${test}`);
for(const test of['work-orchestration-runtime-check.mjs','insight-runtime-check.mjs'])assert.ok(pkg.scripts['test:runtime'].includes(test),`core V3 runtime test not wired: ${test}`);
assert.match(workflow,/V3 orchestration and UX/);
assert.match(workflow,/V3 100k saturation/);
assert.match(workflow,/Canonical V3 guided all-service journey/);
assert.match(workflow,/v3-ux-cutover-check\.mjs/);
assert.match(workflow,/v3-global-dod-check\.mjs/);
for(const heading of['## Global DoD','### V3-S0','### V3-S1','### V3-S2','### V3-S3','### V3-S4','### V3-S5','### V3-S6','### V3-S7','### V3-S8','### V3-S9','## Weld DoD','## UX / terminology / visual-load audit'])assert.ok(dod.includes(heading),`DoD section missing: ${heading}`);
for(const metric of['unifiedWorkQueueCoverage','humanProcedureSelectionCoverage','procedureGuideCoverage','assistEnvelopeCoverage','reviewInboxCoverage','deterministicInsightCoverage','humanInsightValidationCoverage','procedureTraceCoverage','v3Saturation100kCoverage'])assert.equal(contract.experienceMetrics[metric],1,metric);
assert.equal(contract.experienceMetrics.activeUiCompositions,1);
assert.equal(contract.experienceMetrics.roleLeakage,0);
assert.equal(contract.experienceMetrics.humanHeatmapCoverage,1);
assert.equal(contract.experienceMetrics.sameAsReadExportCoverage,1);
console.log('v3-global-dod-check: structural V3 DoD green; exact-head GitHub CI and mergeability remain external seal gates');
