import assert from 'node:assert/strict';
import {execFileSync,spawnSync} from 'node:child_process';
import {mkdtemp,mkdir,writeFile,readFile,rm} from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import {fileURLToPath} from 'node:url';
const root=path.resolve(fileURLToPath(new URL('../../',import.meta.url)));
const source=await readFile(path.join(root,'scripts/release-manifest.mjs'),'utf8');
const run=(cwd,command,args)=>spawnSync(command,args,{cwd,encoding:'utf8',timeout:15000});
const temp=await mkdtemp(path.join(os.tmpdir(),'ictc-manifest-safety-'));
const repo=path.join(temp,'repo');
const cmd=(...args)=>{const r=run(repo,'git',args);assert.equal(r.status,0,r.stderr);};
const commit=()=>{cmd('-c','user.name=ICTC Test','-c','user.email=ci@invalid','commit','-qm','synthetic fixture');};
try{
 await mkdir(path.join(repo,'scripts'),{recursive:true});
 await mkdir(path.join(repo,'src','contracts'),{recursive:true});
 await mkdir(path.join(repo,'artifacts'),{recursive:true});
 await writeFile(path.join(repo,'scripts','release-manifest.mjs'),source);
 await writeFile(path.join(repo,'package.json'),JSON.stringify({name:'ictc',version:'1.8.0'}));
 await writeFile(path.join(repo,'src/contracts/release-identity.json'),JSON.stringify({product:'ICTC',productVersion:'1.8.0',releaseStage:'candidate'}));
 await writeFile(path.join(repo,'code.txt'),'known code');
 await writeFile(path.join(repo,'artifacts','old-manifest.txt'),'preexisting generated data');
 await writeFile(path.join(repo,'.env'),'PRIVATE_KEY=NEVER_EXPOSE_THIS');
 cmd('init','-q');cmd('config','user.name','ICTC Test');cmd('config','user.email','ci@invalid');
 cmd('add','scripts/release-manifest.mjs','package.json','src/contracts/release-identity.json','code.txt');
 commit();
 let r=run(repo,process.execPath,['scripts/release-manifest.mjs']);assert.equal(r.status,0,r.stderr);
 let m=JSON.parse(await readFile(path.join(repo,'artifacts','release-manifest.json'),'utf8'));
 assert.equal(m.releaseApproval,false);assert.equal(m.classification,'non-authoritative-diagnostic');
 assert.equal(m.version,'1.8.0');assert.equal(m.files.length,4);
 assert.deepEqual(m.files.map(x=>x.path).sort(),['code.txt','package.json','scripts/release-manifest.mjs','src/contracts/release-identity.json']);
 assert.ok(!JSON.stringify(m).includes('NEVER_EXPOSE_THIS'));
 let first=m.files.map(x=>[x.path,x.sha256]);
 r=run(repo,process.execPath,['scripts/release-manifest.mjs']);assert.equal(r.status,0);
 m=JSON.parse(await readFile(path.join(repo,'artifacts','release-manifest.json'),'utf8'));
 assert.deepEqual(m.files.map(x=>[x.path,x.sha256]),first,'generated artifacts must not change tracked inventory');
 cmd('add','-f','.env');commit();
 r=run(repo,process.execPath,['scripts/release-manifest.mjs']);assert.notEqual(r.status,0);assert.match(r.stderr,/tracked sensitive\/runtime paths/);
 cmd('rm','-q','--cached','.env');cmd('commit','-qam','drop sensitive tracked path');
 await writeFile(path.join(repo,'package.json'),JSON.stringify({name:'ictc',version:'2.0.0'}));
 r=run(repo,process.execPath,['scripts/release-manifest.mjs']);assert.notEqual(r.status,0);assert.match(r.stderr,/dirty/);
 cmd('add','package.json');commit();
 r=run(repo,process.execPath,['scripts/release-manifest.mjs']);assert.notEqual(r.status,0);assert.match(r.stderr,/identity mismatch/);
 console.log(JSON.stringify({ok:true,scenarios:6,negativeChecks:3,claimBoundary:'synthetic filesystem and Git test; does not certify hosted release'}));
}finally{await rm(temp,{recursive:true,force:true});}
